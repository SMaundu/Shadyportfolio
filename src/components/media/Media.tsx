import { forwardRef, useCallback, useState, type CSSProperties } from "react";
import type { MediaId } from "@/content/media.generated";
import { getMedia } from "@/lib/media";
import { cn } from "@/lib/utils";

export interface MediaProps {
  id: MediaId | null | undefined;
  alt: string;
  /** Responsive `sizes` attribute. Defaults to full viewport width. */
  sizes?: string;
  className?: string;
  style?: CSSProperties;
  fit?: "cover" | "contain";
  /** Load eagerly with high priority (above-the-fold images only). */
  priority?: boolean;
  /** Load immediately but without high priority (e.g. images the user is about to see). */
  eager?: boolean;
  /** Keep the intrinsic aspect ratio instead of filling the parent. */
  intrinsic?: boolean;
  draggable?: boolean;
}

/**
 * Responsive WebP image generated by scripts/assets/build_assets.py.
 * - width/height always set, so layout never shifts while loading
 * - dominant-colour placeholder, then a short fade-in when the image arrives
 * - native lazy loading (never wrapped in masks that would delay it)
 */
export const Media = forwardRef<HTMLImageElement, MediaProps>(function Media(
  { id, alt, sizes = "100vw", className, style, fit = "cover", priority, eager, intrinsic, draggable = false },
  ref,
) {
  const [loaded, setLoaded] = useState(false);
  // Images already in the browser cache report complete before React attaches onLoad.
  const setRef = useCallback(
    (el: HTMLImageElement | null) => {
      if (el?.complete && el.naturalWidth > 0) setLoaded(true);
      if (typeof ref === "function") ref(el);
      else if (ref) ref.current = el;
    },
    [ref],
  );

  const asset = getMedia(id);
  if (!asset) return null;
  const entries = Object.entries(asset.srcs).sort((a, b) => Number(a[0]) - Number(b[0]));
  const srcSet = entries.map(([w, url]) => `${url} ${w}w`).join(", ");
  const fallback = entries[Math.min(1, entries.length - 1)][1];

  return (
    <img
      ref={setRef}
      src={fallback}
      srcSet={srcSet}
      sizes={sizes}
      width={asset.w}
      height={asset.h}
      alt={alt}
      draggable={draggable}
      loading={priority || eager ? "eager" : "lazy"}
      decoding="async"
      // React 18 warns on camelCase fetchPriority; the lowercase attribute is passed through as-is.
      {...({ fetchpriority: priority ? "high" : "auto" } as Record<string, string>)}
      onLoad={() => setLoaded(true)}
      onError={() => setLoaded(true)}
      className={cn(
        intrinsic ? "h-auto w-full" : "h-full w-full",
        fit === "contain" ? "object-contain" : "object-cover",
        "transition-opacity duration-500",
        loaded ? "opacity-100" : "opacity-0",
        className,
      )}
      style={{ backgroundColor: asset.alpha || fit === "contain" ? undefined : asset.color, ...style }}
    />
  );
});
